import type { PrSummaryReview } from "@/automations/agents/pr-summary-reviewer/definition";
import type {
  PullRequestIssueComment,
  PullRequestReviewComment,
} from "@/lib/integrations/github-app";
import type { PreparedPrSummaryDiff } from "./pr-summary-review";

export const COZNT_CAT_SUMMARY_MARKER = "<!-- coznt-cat-summary:v1";

export interface RenderPrSummaryMarkdownInput {
  ownerRepo: string;
  pullNumber: number;
  prTitle: string;
  prBody?: string | null;
  prUrl?: string | null;
  headSha?: string | null;
  review: PrSummaryReview;
  diff: PreparedPrSummaryDiff;
  issueComments: PullRequestIssueComment[];
  reviewComments: PullRequestReviewComment[];
  generatedAt: Date;
}

export function renderPrSummaryMarkdown(input: RenderPrSummaryMarkdownInput): string {
  const effort = estimateReviewEffort(input.diff);
  const labels = suggestLabels(input);
  const relatedIssues = findRelatedRefs(input.prTitle, input.prBody, "issue");
  const relatedPrs = findRelatedRefs(input.prTitle, input.prBody, "pull_request");
  const checks = buildPremergeChecks(input);
  const body = input.prBody?.trim();
  const fileRows = input.review.files.length > 0
    ? input.review.files
        .map((file) => `| ${escapeTable(file.path)} | ${escapeTable(file.changeSummary)} |`)
        .join("\n")
    : "| No file summaries generated. | GitHub file diff data was unavailable or empty. |";

  const failedChecks = checks.filter((check) => check.status === "Warning");
  const passedChecks = checks.filter((check) => check.status === "Passed");
  const reviewContext = [
    `${input.issueComments.length} conversation comment(s)`,
    `${input.reviewComments.length} inline review comment(s)`,
  ].join(", ");

  return trimGitHubComment([
    `${COZNT_CAT_SUMMARY_MARKER} ownerRepo=${input.ownerRepo} pull=${input.pullNumber} sha=${input.headSha ?? "unknown"} -->`,
    "",
    "## PR Author-generated Summary",
    "",
    body || "_No PR description was provided by the author._",
    "",
    "## Coznt Cat-generated Summary",
    "",
    input.review.summary,
    "",
    "### Walkthrough",
    "",
    formatBullets(input.review.notableChanges, input.review.summary),
    "",
    "### Changes",
    "",
    "| File(s) / Path(s) | Change Summary |",
    "|---|---|",
    fileRows,
    "",
    "### Sequence diagram(s)",
    "",
    "_No sequence diagram generated for this summary._",
    "",
    "### Estimated code review effort",
    "",
    `${effort.icon} ${effort.score} (${effort.label}) | ${effort.minutes}`,
    "",
    "### Possibly related issues",
    "",
    formatRelated(relatedIssues, "No related issues found in the PR title or description."),
    "",
    "### Possibly related PRs",
    "",
    formatRelated(relatedPrs, "No related PRs found in the PR title or description."),
    "",
    "### Suggested labels",
    "",
    formatBullets(labels, "No labels suggested."),
    "",
    "### Suggested reviewers",
    "",
    "_No reviewer suggestions generated from the available diff context._",
    "",
    `### Pre-merge checks | ${passedChecks.length} passed | ${failedChecks.length} warning(s)`,
    "",
    `#### Failed checks (${failedChecks.length} warning${failedChecks.length === 1 ? "" : "s"})`,
    "",
    failedChecks.length > 0 ? formatChecksTable(failedChecks, true) : "_No warning checks._",
    "",
    `#### Passed checks (${passedChecks.length} passed)`,
    "",
    passedChecks.length > 0 ? formatChecksTable(passedChecks, false) : "_No passed checks._",
    "",
    "### Finishing Touches",
    "",
    "- Generate docstrings",
    "- Create stacked PR",
    "- Commit on current branch",
    "",
    "### Review context read",
    "",
    reviewContext,
    "",
    input.review.limitations.length > 0 ? "### Limitations" : "",
    input.review.limitations.length > 0 ? "" : "",
    input.review.limitations.length > 0 ? formatBullets(input.review.limitations, "") : "",
    "",
    `_Generated by Coznt Cat at ${input.generatedAt.toISOString()}._`,
  ]);
}

function trimGitHubComment(parts: string[]): string {
  const body = parts.filter((part) => part !== "").join("\n").trim();
  const max = 60_000;
  if (body.length <= max) return body;
  return `${body.slice(0, max)}\n\n_Comment truncated to fit GitHub limits._`;
}

function escapeTable(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
}

function formatBullets(values: string[], fallback: string): string {
  if (values.length === 0) return fallback;
  return values.map((value) => `- ${value}`).join("\n");
}

function estimateReviewEffort(diff: PreparedPrSummaryDiff): {
  icon: string;
  score: number;
  label: string;
  minutes: string;
} {
  const changedLines = diff.files.reduce((sum, file) => sum + file.additions + file.deletions, 0);
  const fileCount = diff.totalFiles;
  const truncated = diff.truncatedFiles || diff.files.some((file) => file.truncatedPatch);

  if (fileCount <= 2 && changedLines <= 50 && !truncated) {
    return { icon: "🎯", score: 1, label: "Low", minutes: "~10 minutes" };
  }
  if (fileCount <= 6 && changedLines <= 180 && !truncated) {
    return { icon: "🎯", score: 2, label: "Light", minutes: "~15 minutes" };
  }
  if (fileCount <= 20 && changedLines <= 700) {
    return { icon: "🎯", score: 3, label: "Moderate", minutes: "~25 minutes" };
  }
  if (fileCount <= 60 && changedLines <= 2_000) {
    return { icon: "🎯", score: 4, label: "High", minutes: "~45 minutes" };
  }
  return { icon: "🎯", score: 5, label: "Very high", minutes: "~60+ minutes" };
}

function suggestLabels(input: RenderPrSummaryMarkdownInput): string[] {
  const labels = new Set<string>();
  const title = input.prTitle.toLowerCase();
  if (/\b(fix|bug|defect|hotfix)\b/.test(title)) labels.add("bug");
  if (/\b(doc|docs|readme)\b/.test(title)) labels.add("docs");

  for (const file of input.diff.files) {
    const path = file.filename.toLowerCase();
    if (path.endsWith(".md") || path.startsWith("docs/")) labels.add("docs");
    if (path.includes("test") || path.includes("spec.")) labels.add("tests");
    if (path.endsWith(".tsx") || path.includes("/components/") || path.includes("/app/")) {
      labels.add("frontend");
    }
    if (
      path.includes("/api/") ||
      path.includes("/services/") ||
      path.includes("/db/") ||
      path.includes("/server/")
    ) {
      labels.add("backend");
    }
  }

  return [...labels].slice(0, 6);
}

function findRelatedRefs(
  title: string,
  body: string | null | undefined,
  kind: "issue" | "pull_request",
): string[] {
  const text = `${title}\n${body ?? ""}`;
  const refs = new Set<string>();
  const issueKeywords = /\b(close[sd]?|fix(e[sd])?|resolve[sd]?|issue|ticket)\s+((?:[\w.-]+\/[\w.-]+)?#\d+)/gi;
  const prKeywords = /\b(pr|pull request|pull-request)\s+((?:[\w.-]+\/[\w.-]+)?#\d+)/gi;
  const regex = kind === "issue" ? issueKeywords : prKeywords;
  let match: RegExpExecArray | null;
  while ((match = regex.exec(text))) {
    refs.add(match[kind === "issue" ? 3 : 2]);
  }
  return [...refs].slice(0, 5).map((ref) => `${ref} - Referenced in the PR title or description.`);
}

interface CheckRow {
  name: string;
  status: "Passed" | "Warning";
  explanation: string;
  resolution?: string;
}

function buildPremergeChecks(input: RenderPrSummaryMarkdownInput): CheckRow[] {
  const hasDescription = (input.prBody?.trim().length ?? 0) >= 20;
  const hasTitle = input.prTitle.trim().length >= 8;
  const fullDiff = !input.diff.truncatedFiles && !input.diff.files.some((file) => file.truncatedPatch);

  return [
    {
      name: "Title check",
      status: hasTitle ? "Passed" : "Warning",
      explanation: hasTitle
        ? "The PR title is descriptive enough for the generated summary."
        : "The PR title is very short.",
      resolution: hasTitle ? undefined : "Use a concise title that states the behavior being changed.",
    },
    {
      name: "Description check",
      status: hasDescription ? "Passed" : "Warning",
      explanation: hasDescription
        ? "The PR includes author-provided context."
        : "The PR description is empty or too short for reviewer context.",
      resolution: hasDescription ? undefined : "Add why the change was made and how it should be reviewed.",
    },
    {
      name: "Diff coverage",
      status: fullDiff ? "Passed" : "Warning",
      explanation: fullDiff
        ? "All fetched diff input fit inside the summary budget."
        : "Some files or patches were truncated before AI summarization.",
      resolution: fullDiff ? undefined : "Review omitted or truncated files manually before merge.",
    },
  ];
}

function formatRelated(values: string[], fallback: string): string {
  if (values.length === 0) return `_${fallback}_`;
  return values.map((value) => `- ${value}`).join("\n");
}

function formatChecksTable(checks: CheckRow[], includeResolution: boolean): string {
  const header = includeResolution
    ? "| Check Name | Status | Explanation | Resolution |\n|---|---|---|---|"
    : "| Check Name | Status | Explanation |\n|---|---|---|";
  const rows = checks
    .map((check) => {
      const status = check.status === "Passed" ? "✅ Passed" : "⚠️ Warning";
      if (!includeResolution) {
        return `| ${escapeTable(check.name)} | ${status} | ${escapeTable(check.explanation)} |`;
      }
      return `| ${escapeTable(check.name)} | ${status} | ${escapeTable(check.explanation)} | ${escapeTable(check.resolution ?? "")} |`;
    })
    .join("\n");
  return `${header}\n${rows}`;
}
