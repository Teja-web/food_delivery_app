import type { PrSummaryReview } from "@/automations/agents/pr-summary-reviewer/definition";
import type {
  PullRequestIssueComment,
  PullRequestReviewComment,
} from "@/lib/integrations/github-app";
import type { GenerateUsage } from "@/lib/ai";
import type { PreparedPrSummaryDiff } from "./pr-summary-review";

export const COZNT_CAT_SUMMARY_MARKER = "<!-- coznt-cat-summary:v1";

export interface RenderPrSummaryMarkdownInput {
  ownerRepo: string;
  pullNumber: number;
  prTitle: string;
  prBody?: string | null;
  prUrl?: string | null;
  headSha?: string | null;
  review: PrSummaryReview;
  diff: PreparedPrSummaryDiff;
  issueComments: PullRequestIssueComment[];
  reviewComments: PullRequestReviewComment[];
  llmUsage?: GenerateUsage | null;
  generatedAt: Date;
}

export function renderPrSummaryMarkdown(input: RenderPrSummaryMarkdownInput): string {
  const relatedIssues = findRelatedRefs(input.prTitle, input.prBody);
  const body = extractPrAuthorSummary(input.prBody);
  const fileRows = input.review.files.length > 0
    ? input.review.files
        .map((file) => `| ${escapeTable(file.path)} | ${escapeTable(file.changeSummary)} |`)
        .join("\n")
    : "| No file summaries generated. | GitHub file diff data was unavailable or empty. |";

  return trimGitHubComment([
    `${COZNT_CAT_SUMMARY_MARKER} ownerRepo=${input.ownerRepo} pull=${input.pullNumber} sha=${input.headSha ?? "unknown"} -->`,
    "",
    "## PR Author-generated Summary",
    "",
    body || "_No PR description was provided by the author._",
    "",
    "## Coznt Cat-generated Summary",
    "",
    input.review.summary,
    "",
    "### Walkthrough",
    "",
    formatBullets(input.review.notableChanges, input.review.summary),
    "",
    "### Changes",
    "",
    "| File(s) / Path(s) | Change Summary |",
    "|---|---|",
    fileRows,
    "",
    "### LLM token usage and cost",
    "",
    formatLlmUsage(input.llmUsage),
    "",
    "### Possibly related issues",
    "",
    formatRelated(relatedIssues, "No related issues found in the PR title or description."),
    "",
    `_Generated by Coznt Cat at ${input.generatedAt.toISOString()}._`,
  ]);
}

function trimGitHubComment(parts: string[]): string {
  const body = parts.filter((part) => part !== "").join("\n").trim();
  const max = 60_000;
  if (body.length <= max) return body;
  return `${body.slice(0, max)}\n\n_Comment truncated to fit GitHub limits._`;
}

function escapeTable(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
}

function formatBullets(values: string[], fallback: string): string {
  if (values.length === 0) return fallback;
  return values.map((value) => `- ${value}`).join("\n");
}

function formatLlmUsage(usage: GenerateUsage | null | undefined): string {
  if (!usage) {
    return "_Token usage was unavailable from the model provider._";
  }
  if (usage.cacheHit) {
    return [
      "| Model | Input tokens | Output tokens | Total tokens | Estimated cost |",
      "|---|---:|---:|---:|---:|",
      `| ${escapeTable(usage.modelId)} | ${formatTokenCount(usage.inputTokens)} | ${formatTokenCount(usage.outputTokens)} | ${formatTokenCount(usage.totalTokens)} | $0.000000 (cache hit) |`,
    ].join("\n");
  }

  return [
    "| Model | Input tokens | Output tokens | Total tokens | Estimated cost |",
    "|---|---:|---:|---:|---:|",
    `| ${escapeTable(usage.modelId)} | ${formatTokenCount(usage.inputTokens)} | ${formatTokenCount(usage.outputTokens)} | ${formatTokenCount(usage.totalTokens)} | ${formatUsd(usage.estimatedCostUsd)} |`,
  ].join("\n");
}

function formatTokenCount(value: number | null): string {
  return value == null ? "unavailable" : value.toLocaleString("en-US");
}

function formatUsd(value: number | null): string {
  if (value == null) return "unavailable";
  if (value > 0 && value < 0.000001) return "<$0.000001";
  return `$${value.toFixed(6)}`;
}

function extractPrAuthorSummary(body: string | null | undefined): string {
  const text = body?.trim();
  if (!text) return "";

  const normalized = text.replace(/\r\n/g, "\n");
  const authorHeader = findHeading(normalized, "PR Author-generated Summary");
  let authorText = authorHeader
    ? normalized.slice(authorHeader.end).trim()
    : normalized;

  const generatedHeaderIndexes = [
    findHeading(authorText, "CodeRabbit-generated Summary")?.start,
    findHeading(authorText, "Summary by CodeRabbit")?.start,
  ].filter((index): index is number => typeof index === "number");

  if (generatedHeaderIndexes.length > 0) {
    authorText = authorText.slice(0, Math.min(...generatedHeaderIndexes)).trim();
  }

  return authorText
    .trim();
}

function findHeading(text: string, heading: string): { start: number; end: number } | null {
  const escaped = heading.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = new RegExp(`(^|\\n)\\s*#{0,6}\\s*${escaped}\\s*(?=\\n|$)`, "i").exec(text);
  if (!match) return null;
  const start = match.index + (match[1] === "\n" ? 1 : 0);
  return { start, end: match.index + match[0].length };
}

function findRelatedRefs(
  title: string,
  body: string | null | undefined,
): string[] {
  const text = `${title}\n${body ?? ""}`;
  const refs = new Set<string>();
  const issueKeywords = /\b(close[sd]?|fix(e[sd])?|resolve[sd]?|issue|ticket)\s+((?:[\w.-]+\/[\w.-]+)?#\d+)/gi;
  const regex = issueKeywords;
  let match: RegExpExecArray | null;
  while ((match = regex.exec(text))) {
    refs.add(match[3]);
  }
  return [...refs].slice(0, 5).map((ref) => `${ref} - Referenced in the PR title or description.`);
}

function formatRelated(values: string[], fallback: string): string {
  if (values.length === 0) return `_${fallback}_`;
  return values.map((value) => `- ${value}`).join("\n");
}
