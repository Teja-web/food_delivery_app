/**
 * generate-hook-rubric — emit the JS port of the canonical rubric.
 *
 * The Claude Code UserPromptSubmit hook can't import TypeScript and can't
 * rely on a node_modules tree (it runs via `npx -y <tarball>`). So the
 * hook bundle ships a hand-rolled `.mjs` port of `src/lib/prompt-quality/
 * rubric.ts`. This script generates that port from the TS source via the
 * TypeScript compiler API and rewrites the body so it's pure-ESM, no
 * Drizzle/Next imports, no type-only constructs.
 *
 * Run after editing the canonical rubric:
 *
 *     pnpm tsx scripts/generate-hook-rubric.ts
 *
 * Commit the generated file. The parity test
 * (`tests/prompt-quality-rubric-parity.test.ts`) verifies on every CI
 * run that the TS canonical and the .mjs port produce byte-identical
 * scores for the test corpus. Bumping `RUBRIC_VERSION` is mandatory on
 * any algorithmic change so the server-side rescore-on-read path knows
 * to refresh older rows.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import * as ts from "typescript";

const repoRoot = resolve(import.meta.dirname, "..", "..");
const tsSrc = join(repoRoot, "src", "lib", "prompt-quality", "rubric.ts");
const jsDst = join(repoRoot, "scripts", "hook-src", "coznt-prompt-quality.mjs");

const source = readFileSync(tsSrc, "utf8");

// Strip all `import type ... from ...` and `import { type ... } from ...`
// — they reference Drizzle types that aren't shipped in the hook bundle.
// ts.transpileModule preserves value-imports; we drop them too because the
// .mjs is self-contained.
const stripped = source
  // Remove `import type { ... } from "...";`
  .replace(/^import\s+type\s+\{[^}]*\}\s+from\s+["'][^"']+["'];?\s*\n/gm, "")
  // Remove any remaining `import ... from "...";` lines (the .mjs has no deps).
  .replace(/^import\s+(?!type\b)[^;]+;\s*\n/gm, "")
  // Drop `export const __rubricInternals` — debug-only, server-side surface.
  .replace(/export const __rubricInternals[\s\S]*$/m, "");

const result = ts.transpileModule(stripped, {
  compilerOptions: {
    module: ts.ModuleKind.ESNext,
    target: ts.ScriptTarget.ES2022,
    removeComments: false,
  },
  fileName: "rubric.ts",
});

const header = `/**
 * JS port of the canonical rubric (src/lib/prompt-quality/rubric.ts).
 *
 * GENERATED by scripts/generate-hook-rubric.ts — do not edit by hand.
 * Re-run the generator and commit the result after editing the TS source.
 * The parity test (tests/prompt-quality-rubric-parity.test.ts) verifies
 * the two implementations produce byte-identical scores.
 */

`;

writeFileSync(jsDst, header + result.outputText, "utf8");
console.log(`[generate-hook-rubric] wrote ${jsDst}`);
